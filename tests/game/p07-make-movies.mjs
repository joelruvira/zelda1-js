#!/usr/bin/env node
// Generator of the P07 oracle scenarios (combat). Run:  node tests/game/p07-make-movies.mjs [knockback|parry|all]
//
// Both start like ow-enemies-spawn.zmv (from tests/oracle/movies/p08-items.sav: slot 1 with the
// wooden sword, magic shield, red ring and 16 hearts; built by tests/game/p08-make-movies.mjs) and
// walk from $77 into $78 (octoroks coming from the edges of the screen):
//  * link-knockback.zmv: Link walks to the middle of the room and waits: octoroks touch him
//    (CheckLinkCollision -> HarmLink -> BeginShove/Link_BeHarmed, shove of $20 pixels, invincibility,
//    hearts lowered by 1/4 with the red ring), several times.
//  * shield-parry.zmv: Link stands still facing an octorok in line with him: its rocks are parried
//    (CheckLinkCollisionPreinit @Parry, Tune0Request = 1, ShotCollidesWithLink); a search over a few
//    positions/facings finds one, played in the ORIGINAL game (oracle).
// Every movie is replayed from power-on in the oracle and checked against its .expect.json.
import { writeFileSync, existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { Oracle } from '../../tools/oracle/lib/nes-oracle.mjs';
import { loadRomFile } from '../../tools/oracle/lib/rom-file.mjs';
import { createMovie, serializeZmv, loadMovie } from '../../tools/oracle/lib/movie.mjs';

const MOVIES = join(import.meta.dirname, '..', 'oracle', 'movies');
const SRAM_REL = 'p08-items.sav'; // relative to tests/oracle/movies (like p11-items.sav)
const B = { A: 0x80, B: 0x40, S: 0x20, T: 0x10, U: 0x08, D: 0x04, L: 0x02, R: 0x01 };
// RAM addresses (numbers only, the generator does not depend on the port).
const RAM = { GameMode: 0x12, RoomId: 0xeb, ObjShoveDir: 0xc0, Tune0Request: 0x604, ShotCollidesWithLink: 0x34b,
  HeartValues: 0x66f, HeartPartial: 0x670 };
const ENTER_78 = 647; // first frame of mode 5 in room $78 in ow-enemies-spawn.zmv

let rom = null;
let sramInit = null;
async function init() {
  if (rom) return;
  rom = loadRomFile();
  const p = join(MOVIES, 'p08-items.sav');
  if (existsSync(p)) sramInit = readFileSync(p);
  else {
    // Reproducible: register a game in the oracle and edit its items (player area $6000-$652F only).
    const { makeItemsSram } = await import('./p08-make-movies.mjs');
    sramInit = await makeItemsSram();
    writeFileSync(p, sramInit);
    console.log('wrote p08-items.sav');
  }
}

const expand = (runs) => runs.flatMap(([n, b]) => Array(n).fill(b));
function prefix() {
  return loadMovie(join(MOVIES, 'ow-enemies-spawn.zmv')).p1.slice(0, ENTER_78);
}

/** Plays `inputs` (then idle up to `extra` frames); calls onFrame(ram, frame, prev) after each frame. */
async function play(inputs, extra, onFrame) {
  const o = await Oracle.create({ rom: rom.bytes, sram: sramInit, powerOnFill: 0 });
  o.handlers.nmi = (n) => o.setButtons(inputs[n - 1] ?? 0, 0);
  let prev = Uint8Array.from(o.ram);
  const total = inputs.length + extra;
  while (o.completedFrames < total) {
    const f = o.completedFrames;
    while (o.completedFrames === f) o.nes.frame();
    if (onFrame(o.ram, o.completedFrames, prev) === true) return o.completedFrames;
    prev = Uint8Array.from(o.ram);
  }
  return -1;
}

const linkShoved = (m, p) => (m[RAM.ObjShoveDir] & 0x80) && !(p[RAM.ObjShoveDir] & 0x80);
// Tune0Request bit 0 at the end of a frame (DriveAudio, earlier in the NMI, consumes the previous one).
const parried = (m) => (m[RAM.Tune0Request] & 0x01) !== 0;

function save(name, inputs, comment, expect) {
  const m = createMovie(inputs, null, { name });
  let text = serializeZmv(m);
  const lines = text.split('\n');
  lines.splice(1, 0, ...comment.map((c) => `# ${c}`));
  text = lines.join('\n');
  writeFileSync(join(MOVIES, `${name}.zmv`), text);
  writeFileSync(join(MOVIES, `${name}.expect.json`), `${JSON.stringify({ sram: SRAM_REL, ...expect }, null, 2)}\n`);
  console.log(`wrote ${name}.zmv (${inputs.length} frames)`);
}

async function makeKnockback() {
  const inputs = [...prefix(), ...expand([[70, B.R]])];
  let hits = 0;
  let last = -1;
  await play(inputs, 3000, (m, f, p) => {
    if (f > ENTER_78 && linkShoved(m, p)) { hits++; last = f; }
    return hits >= 3 && f > last + 60;
  });
  if (hits < 3) throw new Error(`knockback: only ${hits} hits`);
  const end = last + 61;
  while (inputs.length < end) inputs.push(0);
  save('link-knockback', inputs, [
    'P07: from tests/oracle/movies/p08-items.sav, walk $77 -> $78 and wait in the middle of the room:',
    'octoroks touch Link 3 times (HarmLink, BeginShove, Link_BeHarmed with the red ring).',
    'Generated by tests/game/p07-make-movies.mjs. Run the oracle with --sram tests/oracle/movies/p08-items.sav.',
  ], { comment: 'Link is shoved (ObjShoveDir bit 7) and loses hearts in room $78.', reaches: { RoomId: [120], GameMode: [5] },
    events: { linkShoved: 3 } });
}

/** Faces Link towards a monster rock flying at him (one frame on the direction pad), else idle. */
function faceIncomingShot(m) {
  const lx = m[0x70], ly = m[0x84];
  for (let s = 1; s < 0x0c; s++) {
    const t = m[0x34f + s];
    if (t < 0x53 || t >= 0x5b || (m[0xac + s] & 0xf0) !== 0x10) continue;
    const sx = m[0x70 + s], sy = m[0x84 + s], d = m[0x98 + s];
    const rowAligned = Math.abs(sy - ly) < 12, colAligned = Math.abs(sx - lx) < 12;
    let face = 0;
    if (d === 2 && rowAligned && sx > lx) face = 1; // rock flying left: face right
    else if (d === 1 && rowAligned && sx < lx) face = 2;
    else if (d === 8 && colAligned && sy > ly) face = 4;
    else if (d === 4 && colAligned && sy < ly) face = 8;
    if (face && m[0x98] !== face) return { 1: B.R, 2: B.L, 4: B.D, 8: B.U }[face];
  }
  return 0;
}

async function makeParry() {
  const inputs = [...prefix(), ...expand([[70, B.R]])];
  const o = await Oracle.create({ rom: rom.bytes, sram: sramInit, powerOnFill: 0 });
  o.handlers.nmi = (n) => {
    if (inputs.length < n) inputs.push(faceIncomingShot(o.ram));
    o.setButtons(inputs[n - 1], 0);
  };
  let parries = 0, last = -1;
  while (o.completedFrames < 6000) {
    const f = o.completedFrames;
    while (o.completedFrames === f) o.nes.frame();
    if (o.completedFrames > inputs.length - 1 && parried(o.ram)) { parries++; last = o.completedFrames; }
    if (parries >= 2 && o.completedFrames > last + 40) break;
  }
  if (parries < 2) throw new Error(`parry: only ${parries} parries`);
  inputs.length = o.completedFrames;
  // Replay from power-on to confirm.
  let again = 0;
  await play(inputs, 0, (m) => { if (parried(m)) again++; });
  if (again < 2) throw new Error(`parry: replay gave ${again} parries`);
  save('shield-parry', inputs, [
    'P07: from p08-items.sav (magic shield), walk $77 -> $78 and stand in the middle of the room; whenever',
    'an octorok rock flies at Link, he turns to face it (one frame on the pad) and parries it with the shield',
    `(CheckLinkCollisionPreinit @Parry: Tune0Request = 1), ${parries} times; last at frame ${last}.`,
    'Generated by tests/game/p07-make-movies.mjs. Run the oracle with --sram tests/oracle/movies/p08-items.sav.',
  ], { comment: 'Monster rocks are parried by Link (CheckLinkCollisionPreinit @Parry).', reaches: { RoomId: [120], GameMode: [5] },
    events: { parries, last } });
}

if (import.meta.main) {
  await init();
  const what = process.argv[2] ?? 'all';
  if (what === 'knockback' || what === 'all') await makeKnockback();
  if (what === 'parry' || what === 'all') await makeParry();
}
