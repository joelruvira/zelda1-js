// P11: generates the prepared SRAM and the movies of the HUD/submenu scenarios.
//   tests/oracle/movies/p11-items.sav    save slot 1 "AAAAA" (from register-name, played in the
//                                          oracle) with a full-ish inventory, 2 triforce pieces,
//                                          level 1 map and compass, rupees still to add. Only the
//                                          player's save area ($6000-$652F) is kept: no ROM data.
//   tests/oracle/movies/pause-and-menu.zmv  continue that file, open the submenu, move the cursor
//                                          both ways, close it, Select pause, walk (rupees count).
//   tests/oracle/movies/uw-level1-map.zmv  continue, walk $77->$78->$68->$58->$48->$38->$37 and enter
//                                          level 1 (map + compass in the file): submenu with the
//                                          sheet map, status bar map, triforce marker; walk to the next
//                                          room (UW scroll) and open the submenu again.
//     The walk is found by closed-loop control on the oracle: each frame Link's position is read
//     and a BFS over the room's tiles (laid out by the original LayoutRoomOW, run through
//     tests/game/p01-hybrid.mjs) picks the button. The resulting inputs are deterministic.
// Usage: node tests/game/p11-make-movies.mjs [--check]   (--check runs the movies in the oracle)
