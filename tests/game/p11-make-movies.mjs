const BTN_U = 0x08, BTN_D = 0x04, BTN_L = 0x02, BTN_R = 0x01, BTN_T = 0x10;

/** Tiles ($6530, column-major 32 x 22) of every OW room, laid out by the original LayoutRoomOW. */
async function owLayouts(state) {
  const H = await import('./p01-hybrid.mjs');
  const out = new Map();
  for (const room of ROOM_ROUTE) {
    ram.set(state.ram);
    sram.set(state.sram);
    ram[V.RoomId] = room;
    switchBank(5);
    H.runOriginal('LayoutRoomOW');
    out.set(room, Uint8Array.from(sram.subarray(0x530, 0x530 + 0x2c0)));
  }
  return out;
}

const ROOM_ROUTE = [0x77, 0x78, 0x68, 0x58, 0x48, 0x38, 0x37];
const GOAL = { room: 0x37, i: 14, j: 10 }; // below the level 1 entrance (tile $24 at row 9)

/**
 * BFS over Link positions on the 8-pixel grid of one room (node (i, j) = x 8i, y $3D + 8j; valid if
 * the 4 tiles under the 16x16 sprite are walkable). Returns the first step direction towards the
 * goal: the goal node, or the room edge that leads to the next room of ROOM_ROUTE.
 */
function planStep(tiles, room, i0, j0) {
  const walk = (c, r) => c >= 0 && c < 32 && r >= 0 && r < 22 && tiles[c * 22 + r] < 0x89;
  const valid = (i, j) => i >= 0 && i <= 30 && j >= 0 && j <= 20
    && walk(i, j) && walk(i + 1, j) && walk(i, j + 1) && walk(i + 1, j + 1);
  const next = ROOM_ROUTE[ROOM_ROUTE.indexOf(room) + 1];
  const exitDir = next === undefined ? 0 : next === room + 1 ? BTN_R : next === room - 1 ? BTN_L
    : next === room - 16 ? BTN_U : BTN_D;
  const isGoal = (i, j) => (room === GOAL.room ? i === GOAL.i && j === GOAL.j
    : exitDir === BTN_R ? i === 30 : exitDir === BTN_L ? i === 0 : exitDir === BTN_U ? j === 0 : j === 20);
  const key = (i, j) => j * 32 + i;
  const first = new Map();
  const q = [[i0, j0]];
  first.set(key(i0, j0), 0);
  const moves = [[BTN_U, 0, -1], [BTN_D, 0, 1], [BTN_L, -1, 0], [BTN_R, 1, 0]];
  while (q.length) {
    const [i, j] = q.shift();
    const f = first.get(key(i, j));
    if (isGoal(i, j)) return f || (room === GOAL.room ? BTN_U : exitDir);
    for (const [b, di, dj] of moves) {
      const ni = i + di, nj = j + dj;
      if (!valid(ni, nj) || first.has(key(ni, nj))) continue;
      first.set(key(ni, nj), f || b);
      q.push([ni, nj]);
    }
  }
  return 0;
}

const AFTER_ENTRY = [
  [90, 0], [2, BTN_T], [100, 0], // submenu: sheet map with the position marker, map and compass
  [2, BTN_R], [12, 0], [2, BTN_L], [12, 0], [2, BTN_T], [100, 0], // cursor, close
  [150, BTN_U], [200, 0], // walk north into the next room (UW scroll, mode 7)
  [2, BTN_T], [100, 0], [2, BTN_T], [100, 0], [1, 0], // submenu again from the new room
];

async function makeUwMovie(sav) {
  const prefix = parseZmv(zmv([], CONTINUE), 'p');
  const pre = await oracleRun(join(MOVIES, '..', 'movies', 'pause-and-menu.zmv'), sav); // any mode-5 state
  const layouts = await owLayouts({ ram: pre[400].ram, sram: pre[400].sram });
  const oracle = await Oracle.create({ rom: romBytes, sram: sav, powerOnFill: 0 });
  const inputs = [];
  let script = null; // scripted inputs once in level 1
  const STOP = {};
  const decide = () => {
    const n = inputs.length;
    if (n < prefix.length) return prefix.p1[n];
    const r = oracle.ram;
    if (script) {
      if (!script.length) throw STOP;
      return script.shift();
    }
    if (r[V.CurLevel] === 1) {
      if (r[V.GameMode] === 5 && r[V.IsUpdatingMode]) script = AFTER_ENTRY.flatMap(([k, b]) => Array(k).fill(b));
      return 0;
    }
    if (r[V.GameMode] !== 5 || !r[V.IsUpdatingMode]) return 0;
    const room = r[V.RoomId];
    const x = r[V.ObjX], y = r[V.ObjY];
    const i = Math.round(x / 8), j = Math.round((y - 0x3d) / 8);
    if (n > 20000) throw new Error('uw-level1-map: walk did not reach level 1');
    return planStep(layouts.get(room), room, Math.max(0, Math.min(30, i)), Math.max(0, Math.min(20, j)));
  };
  const p1 = new Proxy([], { get: (t, k) => {
    if (k === 'length') return 1e9;
    const v = decide();
    inputs.push(v);
    return v;
  } });
  try {
    oracle.run({ timing: 'nmi', length: 1e6, p1, p2: new Proxy([], { get: () => 0 }) }, { write() {} });
  } catch (e) {
    if (e !== STOP) throw e;
  }
  inputs.pop(); // the read that hit STOP
  const runs = [];
  for (let k = 0; k < inputs.length;) {
    let e = k;
    while (e < inputs.length && inputs[e] === inputs[k]) e++;
    runs.push(`${e - k} ${formatButtons(inputs[k])}`);
    k = e;
  }
  return zmv([
    'P11: continue the prepared file (tests/oracle/movies/p11-items.sav: level 1 map and compass), walk',
    '$77 -> $78 -> $68 -> $58 -> $48 -> $38 -> $37 and enter level 1; open the submenu (sheet map, marker),',
    'move the cursor, close; walk north into the next room; open and close the submenu again.',
    'Generated by tests/game/p11-make-movies.mjs (closed-loop walk). Run with --sram tests/oracle/movies/p11-items.sav.',
  ], runs);
}

async function main() {
  const sav = await makeSram();
  writeFileSync(join(MOVIES, 'p11-items.sav'), sav);
  writeFileSync(join(MOVIES, 'pause-and-menu.zmv'), PAUSE_AND_MENU);
  console.log('wrote p11-items.sav, pause-and-menu.zmv');
  writeFileSync(join(MOVIES, 'uw-level1-map.zmv'), await makeUwMovie(sav));
  console.log('wrote uw-level1-map.zmv');
  if (process.argv.includes('--check')) {
    const which = process.argv.includes('--uw') ? 'uw-level1-map.zmv' : 'pause-and-menu.zmv';
    const frames = await oracleRun(join(MOVIES, which), sav);
    let prev = '';
    frames.forEach((f, i) => {
      const r = f.ram;
      const s = `lvl ${r[V.CurLevel]} mode ${r[V.GameMode]} sub ${r[V.GameSubmode]} menu ${r[V.MenuState]} sel ${r[V.SelectedItemSlot]} vs ${r[V.CurVScroll]} room ${r[V.RoomId].toString(16)} rup ${r[V.InvRupees]} paused ${r[V.Paused]}`;
      if (s.replace(/vs \d+ /, '') !== prev) console.log(i, s);
      prev = s.replace(/vs \d+ /, '');
    });
  }
}

main();
