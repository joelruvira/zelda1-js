/** Final SRAM after playing `movieFile` in the oracle (from power-on, empty SRAM). */
async function oracleRun(movieFile, sramInit = null) {
  const movie = parseZmv(readFileSync(movieFile, 'utf8'), 'm');
  const oracle = await Oracle.create({ rom: romBytes, sram: sramInit, powerOnFill: 0 });
  const frames = [];
  oracle.run(movie, { write: (rec) => frames.push({ ram: rec.ram, sram: rec.sram }) });
  return frames;
}

// Items block offsets (from Items = $657) and values for the prepared file.
const ITEMS = {
  [V.Items]: 0x01, // wooden sword
  [V.InvBombs]: 0x04,
  [V.InvArrow]: 0x01,
  [V.Bow]: 0x01,
  [V.InvCandle]: 0x01,
  [V.InvFood]: 0x01,
  [V.Potion]: 0x00,
  [V.InvRing]: 0x01, // blue ring: Link survives the walks
  [V.InvLetter]: 0x01,
  [V.InvBracelet]: 0x01,
  [V.InvCompass]: 0x01, // level 1
  [V.InvMap]: 0x01, // level 1
  [V.InvRupees]: 0x2a,
  [V.InvKeys]: 0x03,
  [V.HeartValues]: 0x77, // 8 containers, 8 hearts
  [V.HeartPartial]: 0xff,
  [V.InvTriforce]: 0x05, // pieces 1 and 3
  [V.InvBoomerang]: 0x01,
  [V.MaxBombs]: 0x08,
  [V.RupeesToAdd]: 0x0c,
};

async function makeSram() {
  const frames = await oracleRun(join(MOVIES, 'register-name.zmv'));
  const last = frames.at(-1).sram;
  const sav = new Uint8Array(0x2000);
  sav.set(last.subarray(0, 0x530)); // $6000-$652F: save files A, markers, checksums
  // Patch slot 0 items and recompute its checksum with the port's routines (P24).
  await loadSymbols();
  createMachine(loadRom(romBytes));
  sram.set(sav);
  switchBank(1);
  CopyCommonCodeToRam(); // FetchFileAAddressSet reads its table from the WRAM copy
  for (const [addr, v] of Object.entries(ITEMS)) sram[V.SaveFileAItems0 - 0x6000 + (addr - V.Items)] = v;
  ram[V.CurSaveSlot] = 0;
  FetchFileAAddressSet();
  CalculateFileAChecksum();
  sram[V.FileAChecksums - 0x6000] = ram[0x0e];
  sram[V.FileAChecksums + 1 - 0x6000] = ram[0x0f];
  sav.set(sram.subarray(0, 0x530));
  return sav;
}

function zmv(comment, runs) {
  return ['zmv 1', ...comment.map((c) => `# ${c}`), 'timing nmi', ...runs].join('\n') + '\n';
}

