// P19 in the pure port (no hybrid): the underworld-monster tours run through src/headless.js against the
// oracle (RAM + SRAM, every frame), whole movie, diff 0 required.
//  * uw-enemies-a (first quest, SRAM p19-items.sav): goriyas (boomerangs), ropes, gels, zols (hit: two
//    gels), keeses, flashing bubbles, red/blue darknuts, vires (hit: two red keeses), like like, pols voice
//    (recorder, then arrows), gibdos, stalfos; bombed walls and cleared shutters on the way.
//  * uw-enemies-a2 (second quest, SRAM p19-items-q2.sav): zol split and a like like eating the magic
//    shield in level 4, stalfos throwing sword shots in level 1.
// Generated by tests/game/p19-make-movies.mjs. Skipped without roms/zelda.nes or jsnes.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { join, basename } from 'node:path';
import { readFileSync, existsSync } from 'node:fs';
import { hasJsnes } from '../../tools/oracle/lib/jsnes-loader.mjs';
import { romExists, loadRomFile } from '../../tools/oracle/lib/rom-file.mjs';
import { loadMovie } from '../../tools/oracle/lib/movie.mjs';
import { TraceCollector } from '../../tools/oracle/lib/trace.mjs';
import { compareTraces, loadIgnoreConfig } from '../../tools/oracle/lib/diff-core.mjs';
import { runPort } from '../../tools/oracle/lib/port-adapter.mjs';
import { ROOT } from '../core/helpers.mjs';

const skip = !romExists() ? 'roms/zelda.nes not present' : !(await hasJsnes()) ? 'jsnes not installed' : false;
const MOVIES = join(ROOT, 'tests/oracle/movies');

for (const name of ['uw-enemies-a', 'uw-enemies-a2']) {
  const missing = !existsSync(join(MOVIES, `${name}.zmv`)) && `${name}.zmv not generated`;
  test(`P19 pure port ${name}: diff 0 on every frame`, { skip: skip || missing, timeout: 1800000 }, async (t) => {
    const rom = loadRomFile();
    const expect = JSON.parse(readFileSync(join(MOVIES, `${name}.expect.json`), 'utf8'));
    const sram = new Uint8Array(readFileSync(join(MOVIES, basename(expect.sram))));
    const movie = loadMovie(join(MOVIES, `${name}.zmv`));
    const { Oracle } = await import('../../tools/oracle/lib/nes-oracle.mjs');
    const V = await import('../../src/core/vars.js');
    const a = new TraceCollector({});
    const types = new Set();
    (await Oracle.create({ rom: rom.bytes, sram, powerOnFill: 0 })).run(movie, {
      write(rec) {
        a.write(rec);
        for (let i = 1; i < 0x0c; i++) types.add(rec.ram[V.ObjType + i]);
      },
      close() {},
    });
    for (const ty of expect.monsterTypes) assert.ok(types.has(ty), `${name}: no monster of type $${ty.toString(16)}`);
    const b = new TraceCollector({});
    await runPort({ rom: rom.bytes, sram, inputs: movie, sink: b });
    t.diagnostic(`${b.frames.length} frames; events: ${expect.events.join('; ')}`);
    const report = compareTraces(a, b, { ignore: loadIgnoreConfig().ignore, compareFb: false });
    const first = report.frames[0];
    assert.equal(report.divergentFrames, 0, `${name}: first divergence at frame ${report.firstDivergence}: `
      + JSON.stringify(first && { ram: first.ram.slice(0, 8), sram: first.sram.slice(0, 8) }));
  });
}
