// P20 in the pure port (no hybrid): the underworld-monster tour B runs through src/headless.js against the
// oracle (RAM + SRAM, every frame), whole movie, diff 0 required.
//  * uw-enemies-b (first quest, SRAM p20-items.sav): Death Mountain (rock pushed with the bracelet,
//    shortcut stairs), Spectacle Rock bombed, level 9: blue and red wizzrobes (magic shots), red lamnolas;
//    level 6: red wizzrobes, statue fireballs, traps; level 1: a wallmaster carries Link back to the
//    entrance (mode 3).
//  * uw-enemies-b2 (second quest, SRAM p20-items-q2.sav): level 4: wizzrobes with red and blue bubbles,
//    black keeses (the second-quest monsters of P19 missing from uw-enemies-a/a2), traps, zols, like likes.
// Generated by tests/game/p20-make-movies.mjs. Skipped without roms/zelda.nes or jsnes.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { join, basename } from 'node:path';
import { readFileSync, existsSync } from 'node:fs';
import { hasJsnes } from '../../tools/oracle/lib/jsnes-loader.mjs';
import { romExists, loadRomFile } from '../../tools/oracle/lib/rom-file.mjs';
import { loadMovie } from '../../tools/oracle/lib/movie.mjs';
import { TraceCollector } from '../../tools/oracle/lib/trace.mjs';
import { compareTraces, loadIgnoreConfig } from '../../tools/oracle/lib/diff-core.mjs';
import { runPort } from '../../tools/oracle/lib/port-adapter.mjs';
import { ROOT } from '../core/helpers.mjs';

const skip = !romExists() ? 'roms/zelda.nes not present' : !(await hasJsnes()) ? 'jsnes not installed' : false;
const MOVIES = join(ROOT, 'tests/oracle/movies');
// Monster types each movie must show: wizzrobes, wallmaster, red lamnola, traps; in the second quest also
// the blue/red bubbles and the black keese.
const REQUIRED = {
  'uw-enemies-b': [0x23, 0x24, 0x27, 0x3a, 0x49],
  'uw-enemies-b2': [0x23, 0x24, 0x2c, 0x2d, 0x1d, 0x49],
};

for (const name of Object.keys(REQUIRED)) {
  const missing = !existsSync(join(MOVIES, `${name}.zmv`)) && `${name}.zmv not generated`;
  test(`P20 pure port ${name}: diff 0 on every frame`, { skip: skip || missing, timeout: 1800000 }, async (t) => {
    const rom = loadRomFile();
    const expect = JSON.parse(readFileSync(join(MOVIES, `${name}.expect.json`), 'utf8'));
    const sram = new Uint8Array(readFileSync(join(MOVIES, basename(expect.sram))));
    const movie = loadMovie(join(MOVIES, `${name}.zmv`));
    const { Oracle } = await import('../../tools/oracle/lib/nes-oracle.mjs');
    const V = await import('../../src/core/vars.js');
    const a = new TraceCollector({});
    const types = new Set();
    const modes = new Set();
    (await Oracle.create({ rom: rom.bytes, sram, powerOnFill: 0 })).run(movie, {
      write(rec) {
        a.write(rec);
        modes.add(rec.ram[V.GameMode]);
        for (let i = 1; i < 0x0c; i++) types.add(rec.ram[V.ObjType + i]);
      },
      close() {},
    });
    for (const ty of [...REQUIRED[name], ...expect.monsterTypes]) assert.ok(types.has(ty), `${name}: no monster of type $${ty.toString(16)}`);
    for (const m of expect.reaches.GameMode ?? []) assert.ok(modes.has(m), `${name}: never in mode $${m.toString(16)}`);
    const b = new TraceCollector({});
    await runPort({ rom: rom.bytes, sram, inputs: movie, sink: b });
    t.diagnostic(`${b.frames.length} frames; events: ${expect.events.join('; ') || 'none'}`);
    const report = compareTraces(a, b, { ignore: loadIgnoreConfig().ignore, compareFb: false });
    const first = report.frames[0];
    assert.equal(report.divergentFrames, 0, `${name}: first divergence at frame ${report.firstDivergence}: `
      + JSON.stringify(first && { ram: first.ram.slice(0, 8), sram: first.sram.slice(0, 8) }));
  });
}
