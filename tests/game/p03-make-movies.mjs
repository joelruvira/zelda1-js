// Generates tests/oracle/movies/register-zelda-q2.zmv (P03): register the name "ZELDA" (second quest),
// back to the menu and start it, so mode 2 runs UpdateMode2Load_Full@PatchQ2Rooms.
// Usage: node tests/game/p03-make-movies.mjs
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../oracle/movies/register-zelda-q2.zmv');
const COLS = 11; // character board: A-K / L-V / W-Z ...
const pos = (ch) => { const i = ch.charCodeAt(0) - 65; return [Math.floor(i / COLS), i % COLS]; };

const lines = ['zmv 1',
  '# P03: title -> menu -> register "ZELDA" (second quest) -> End -> menu -> start the Q2 file.',
  '# Generated by tests/game/p03-make-movies.mjs.', 'timing nmi',
  '120 .', '2 T', '90 .', '# Start on "Register your name": mode $E', '2 T', '90 .'];
let [r, c] = [0, 0];
for (const ch of 'ZELDA') {
  const [tr, tc] = pos(ch);
  lines.push(`# ${ch}`);
  for (; r < tr; r++) lines.push('2 D', '8 .');
  for (; r > tr; r--) lines.push('2 U', '8 .');
  for (; c < tc; c++) lines.push('2 R', '8 .');
  for (; c > tc; c--) lines.push('2 L', '8 .');
  lines.push('2 A', '8 .');
}
lines.push('# Select x3: slot 1 -> 2 -> 3 -> "End"', '2 S', '8 .', '2 S', '8 .', '2 S', '8 .',
  '# Start on "End": back to the menu', '2 T', '90 .', '# start the registered (Q2) file', '2 T', '240 .');
writeFileSync(OUT, lines.join('\n') + '\n');
console.log(OUT);
