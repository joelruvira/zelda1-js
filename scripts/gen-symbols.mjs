#!/usr/bin/env node
// Generates src/core/symbols.js: bank + CPU address of every label in the disassembly.
// It assembles the sources with scripts/lib/asm65.mjs (sizes only, no ROM needed),
// checks every .INCBIN position against bins.xml, and writes names/addresses only.
//
// Usage: node scripts/gen-symbols.mjs [disasmSrcDir] [outFile]

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assemble, bankFingerprints } from './lib/asm65.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = process.argv[2] ?? join(root, 'reference/zelda1-disassembly/src');
const outFile = process.argv[3] ?? join(root, 'src/core/symbols.js');

const { symbols, segments, problems, banks, statements } = assemble(srcDir, { emit: true });
if (problems.length) {
  console.error('gen-symbols: layout does not match bins.xml:\n  ' + problems.join('\n  '));
  process.exit(1);
}

const hex = (v) => '0x' + v.toString(16).toUpperCase().padStart(4, '0');
const KIND = { code: 'c', data: 'd', end: 'e' };

let js = `// GENERATED by scripts/gen-symbols.mjs from the disassembly (Z_0*.asm, Z.cfg, bins.xml). Do not edit.
// Label -> location only; contains no ROM bytes.
//
// SYMBOLS[key] = [bank, cpuAddr, size, kind, loadAddr?]
//   key      Label name; "Name#bank" when several banks define the same name;
//            cheap locals are "Scope@Local".
//   cpuAddr  address the code uses at run time (for BANK_01_CODE / BANK_06_DATA this is
//            the SRAM copy at $6C90.. / $67F0..).
//   size     bytes until the next label (globals: next global label).
//   kind     'c' code, 'd' data, 'e' end-of-segment label.
//   loadAddr only present when the label lives in a segment copied to RAM: the address
//            of the bytes inside the switchable bank ($8000-$BFFF) in the ROM.

/** Linker segments: bank, load address (in ROM), run address, size. */
export const SEGMENTS = Object.freeze({
`;
for (const s of segments.values()) {
  js += `  ${s.name}: { bank: ${s.bank}, load: ${hex(s.load)}, run: ${hex(s.run)}, size: ${hex(s.size)} },\n`;
}
js += `});\n\nexport const SYMBOLS = Object.freeze({\n`;
const sorted = [...symbols.values()].sort((a, b) => a.bank - b.bank || a.load - b.load);
for (const x of sorted) {
  const key = /^[A-Za-z_][A-Za-z0-9_]*$/.test(x.key) ? x.key : `'${x.key}'`;
  const load = x.load !== x.addr ? `, ${hex(x.load)}` : '';
  js += `  ${key}: [${x.bank}, ${hex(x.addr)}, ${x.size}, '${KIND[x.kind]}'${load}],\n`;
}
js += `});\n`;

// Fingerprint of the ROM revision the disassembly describes (US PRG0): CRC32 per bank of
// the assembled bytes outside .INCBIN blocks (unused space = $FF fill). A one-way hash, no data.
js += `\n/** CRC32 per PRG bank of the non-INCBIN bytes of the expected ROM (see rom.js checkRevision). */\n`;
js += `export const PRG_FINGERPRINT = Object.freeze([${bankFingerprints(banks).map((c) => '0x' + c.toString(16).padStart(8, '0')).join(', ')}]);\n`;

const ranges = [];
for (const sts of statements.values()) for (const st of sts) {
  if (st.kind === 'incbin') ranges.push([st.binOffset, st.size]);
}
ranges.sort((a, b) => a[0] - b[0]);
js += `\n/** [prgOffset, length] of every .INCBIN block (from bins.xml), skipped by the fingerprint. */\n`;
js += `export const INCBIN_RANGES = Object.freeze([\n${ranges.map(([o, l]) => `  [${o}, ${l}],`).join('\n')}\n]);\n`;

writeFileSync(outFile, js);
console.log(`gen-symbols: ${symbols.size} labels in ${segments.size} segments -> ${outFile}`);
