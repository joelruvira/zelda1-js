#!/usr/bin/env node
// Generates src/core/vars.js from the disassembly's *.inc files (RAM/SRAM/IO map).
// Output contains only names -> addresses (no ROM data).
//
// Usage: node scripts/gen-vars.mjs [disasmSrcDir] [outFile]

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = process.argv[2] ?? join(root, 'reference/zelda1-disassembly/src');
const outFile = process.argv[3] ?? join(root, 'src/core/vars.js');

// Order matters only for documentation; every .inc is parsed.
const incFiles = readdirSync(srcDir).filter((f) => f.endsWith('.inc')).sort((a, b) =>
  a === 'Variables.inc' ? -1 : b === 'Variables.inc' ? 1 : a.localeCompare(b));

function parseNumber(text) {
  text = text.trim();
  if (text.startsWith('$')) return parseInt(text.slice(1), 16);
  if (text.startsWith('%')) return parseInt(text.slice(1), 2);
  if (/^\d+$/.test(text)) return parseInt(text, 10);
  return NaN;
}

/** Parse one .inc file -> [{name, value, kind, file, line}] */
export function parseInc(text, file) {
  const out = [];
  text.split(/\r?\n/).forEach((raw, i) => {
    const line = raw.replace(/;.*$/, '').trim();
    if (!line) return;
    const m = line.match(/^([A-Za-z_][A-Za-z0-9_]*)\s*(:=|=)\s*(.+)$/);
    if (!m) return;
    const value = parseNumber(m[3]);
    if (Number.isNaN(value)) throw new Error(`${file}:${i + 1}: unsupported expression "${m[3]}"`);
    // ":=" defines an address label; "=" a plain constant.
    out.push({ name: m[1], value, kind: m[2] === ':=' ? 'addr' : 'const', file, line: i + 1 });
  });
  return out;
}

function region(addr) {
  if (addr < 0x800) return 'ram';
  if (addr >= 0x2000 && addr < 0x2008) return 'ppu';
  if (addr >= 0x4000 && addr < 0x4020) return 'apu';
  if (addr >= 0x6000 && addr < 0x8000) return 'sram';
  return 'other';
}

const entries = [];
for (const f of incFiles) entries.push(...parseInc(readFileSync(join(srcDir, f), 'utf8'), f));

// Detect conflicting redefinitions (same name, different value).
const byName = new Map();
for (const e of entries) {
  const prev = byName.get(e.name);
  if (prev && prev.value !== e.value) {
    throw new Error(`Conflicting definitions for ${e.name}: ${prev.file}=${prev.value} vs ${e.file}=${e.value}`);
  }
  if (!prev) byName.set(e.name, e);
}

// Size hint: distance to the next distinct address within the same file and region
// (approximate; arrays like ObjX span until the next variable).
const sizes = new Map();
for (const f of incFiles) {
  const addrs = [...new Set(entries.filter((e) => e.file === f && e.kind === 'addr').map((e) => e.value))].sort((a, b) => a - b);
  for (const e of entries.filter((x) => x.file === f && x.kind === 'addr')) {
    const next = addrs.find((a) => a > e.value && region(a) === region(e.value));
    if (next !== undefined && next - e.value <= 0x100) sizes.set(e.name, next - e.value);
  }
}

const hex = (v, w = 4) => '0x' + v.toString(16).toUpperCase().padStart(w, '0');
let js = `// GENERATED by scripts/gen-vars.mjs from the disassembly's *.inc files. Do not edit.
// Names and addresses only (RAM $0000-$07FF, SRAM $6000-$7FFF, IO registers).
// Several names alias the same address (the original reuses RAM per game mode).

`;
for (const f of incFiles) {
  js += `// ---- ${f} ----\n`;
  for (const e of entries.filter((x) => x.file === f)) {
    if (byName.get(e.name) !== e) continue;
    js += `export const ${e.name} = ${e.kind === 'addr' ? hex(e.value) : e.value};\n`;
  }
  js += '\n';
}
js += `/** Approximate size in bytes of each address variable (gap to the next variable in its .inc). */\nexport const VAR_SIZE = Object.freeze({\n`;
for (const [name, size] of sizes) js += `  ${name}: ${size},\n`;
js += `});\n\n/** Region of each address variable: ram | sram | ppu | apu. */\nexport const VAR_REGION = Object.freeze({\n`;
for (const e of byName.values()) if (e.kind === 'addr') js += `  ${e.name}: '${region(e.value)}',\n`;
js += `});\n`;

writeFileSync(outFile, js);
console.log(`gen-vars: ${byName.size} symbols from ${incFiles.length} files -> ${outFile}`);
