// Locations shared by the Android scripts: SDK, adb, Gradle wrapper, outputs.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, resolve, dirname } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

export const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export const ANDROID_DIR = join(REPO, 'android');
export const DIST = join(REPO, 'dist');
export const RELEASE_APK = join(DIST, 'zelda1-js.apk');
export const DEBUG_APK = join(DIST, 'zelda1-js-debug.apk');
export const APP_ID = 'io.github.joelruvira.zelda1js';
export const DEBUG_APP_ID = `${APP_ID}.debug`;
export const IS_WINDOWS = process.platform === 'win32';

/** The Android SDK: local.properties, $ANDROID_HOME / $ANDROID_SDK_ROOT or the usual install folder. */
export function findSdk() {
  const lp = join(ANDROID_DIR, 'local.properties');
  if (existsSync(lp)) {
    const m = /^sdk\.dir=(.*)$/m.exec(readFileSync(lp, 'utf8'));
    if (m) {
      const dir = m[1].trim().replace(/\\:/g, ':').replace(/\\\\/g, '\\');
      if (existsSync(dir)) return dir;
    }
  }
  const candidates = [
    process.env.ANDROID_HOME, process.env.ANDROID_SDK_ROOT,
    join(homedir(), 'Library/Android/sdk'), // macOS (Android Studio)
    join(homedir(), 'Android/Sdk'), // Linux
    process.env.LOCALAPPDATA && join(process.env.LOCALAPPDATA, 'Android/Sdk'), // Windows
  ].filter(Boolean);
  return candidates.find((d) => existsSync(join(d, 'platforms'))) ?? null;
}

/** Writes android/local.properties (git-ignored) when it is missing, so Gradle finds the SDK. */
export function ensureLocalProperties(sdk) {
  const lp = join(ANDROID_DIR, 'local.properties');
  if (existsSync(lp)) return;
  const escaped = sdk.replace(/\\/g, '\\\\').replace(/:/g, '\\:');
  writeFileSync(lp, `# Generated by scripts/android (not in git)\nsdk.dir=${escaped}\n`);
}

export function findAdb() {
  const sdk = findSdk();
  const exe = IS_WINDOWS ? 'adb.exe' : 'adb';
  if (sdk && existsSync(join(sdk, 'platform-tools', exe))) return join(sdk, 'platform-tools', exe);
  return 'adb';
}

/**
 * Environment for Gradle and keytool: when there is no JAVA_HOME and no `java` on the PATH, use the JDK that
 * comes inside Android Studio (so installing Android Studio is enough).
 */
export function javaEnv() {
  const env = { ...process.env };
  if (env.JAVA_HOME) return env;
  const probe = spawnSync(IS_WINDOWS ? 'java.exe' : 'java', ['-version'], { stdio: 'ignore' });
  if (!probe.error && probe.status === 0) return env;
  const studio = [
    '/Applications/Android Studio.app/Contents/jbr/Contents/Home',
    process.env.ProgramFiles && join(process.env.ProgramFiles, 'Android/Android Studio/jbr'),
    '/opt/android-studio/jbr', join(homedir(), 'android-studio/jbr'),
  ].filter(Boolean).find((d) => existsSync(join(d, 'bin')));
  if (studio) {
    env.JAVA_HOME = studio;
    process.env.JAVA_HOME = studio;
  }
  return env;
}
